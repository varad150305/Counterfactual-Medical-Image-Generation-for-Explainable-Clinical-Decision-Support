#!/usr/bin/env python
"""Research demo of the completed counterfactual pipeline (A0 / A-ft / B / C). A command-line tool, not a product.

Every output (panel image, JSON card, console text) is labelled as a SYNTHETIC RESEARCH OUTPUT that is not clinically validated.
Classifier scores shown here come from a frozen model trained on automatic CheXpert labels; B and C were optimised against it,
so a high score is NOT evidence of a correct or clinically valid edit (docs/FINAL_RESEARCH_REPORT.md sections 3.4-3.5).

Commands (details and artifact locations: README.md):
  cases     list the 24 held-out evaluation cases with the four arms' saved scores            (CPU, offline, needs the saved artifacts)
  show      side-by-side panel original | A0 | A-ft | B | C for one case from the saved outputs  (CPU, offline, needs the saved artifacts)
  generate  run the existing PRISM-style pipeline live on ONE image for one arm                (GPU in practice; needs the PRISM checkpoint
            and, for A-ft / B / C, that arm's trained weight overlay `delta_final.safetensors`, which is NOT in the repository)

The app only wires existing, tested code: src/inference/prism_baseline.py (generation), src/evaluation (metrics), the saved Phase 6/7
artifacts (show/cases). It contains no model or loss logic.
"""
import argparse
import json
import os
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402
from PIL import Image  # noqa: E402

DISCLAIMER = ("SYNTHETIC COUNTERFACTUAL IMAGES - RESEARCH OUTPUT ONLY. The edited images are generated by a research model: they are not real patient "
              "images, not clinically validated, and not for diagnosis, treatment or any medical decision.")
SCORE_NOTE = ("Classifier scores: a frozen DenseNet121 trained on automatic CheXpert labels. B and C were optimised against it, so a high score is NOT "
              "evidence of a correct edit (A-ft already reaches ~0.8 with moderate edits; B/C reach 0.95-0.98 while the image degrades).")
ARM_TITLE = {"A0": "A0  untouched PRISM", "A_ft": "A-ft  diffusion-only control", "B": "B  + disease loss (λ1=0.5)", "C": "C  + preservation loss (λ2=10)"}
ARM_FINDING = {"A0": "reference", "A_ft": "reference (moderate edits)", "B": "report: collapsed anatomy in 24/24 edits", "C": "report: exaggerated edits, hallucinated devices"}
ARMS = ("A0", "A_ft", "B", "C")
EVALUATED = ("Cardiomegaly", "add")      # the only operation evaluated in this project


class DemoError(Exception):
    """A clear, user-facing failure (missing artifact, bad argument). Never replaced by a made-up result."""


# ----------------------------------------------------------------------------- saved artifacts (cases / show)
def _p8():
    from src.evaluation import phase8 as P8

    return P8


def locate_artifacts(phase6_op, phase7_op) -> dict:
    """arm -> {run_dir, scores}. Reads the Phase 6 v2 and Phase 7 Kaggle outputs; raises DemoError naming exactly what is missing."""
    P8 = _p8()
    roots = {"phase6": phase6_op, "phase7": phase7_op}
    missing, out = [], {}
    for key, root in roots.items():
        if not root or not Path(root).is_dir():
            missing.append(f"{key} output directory ({'not given' if not root else root})")
    if missing:
        raise DemoError("saved artifacts not found: " + "; ".join(missing) +
                        ". Pass --phase6-op / --phase7-op (or set PRISM_PHASE6_OP / PRISM_PHASE7_OP); see README.md 'Saved artifacts'.")
    for arm, (key, run_name, rel) in P8.ARM_SOURCES.items():
        root = Path(roots[key])
        scores = root / rel
        try:
            run_dir = P8.first_run_dir(root, run_name)
        except (FileNotFoundError, OSError):
            raise DemoError(f"run directory for arm {arm} not found: {root / run_name}")
        if not scores.exists():
            raise DemoError(f"stored per-image scores for arm {arm} not found: {scores}")
        out[arm] = {"run_dir": run_dir, "scores": pd.read_csv(scores).sort_values("index").reset_index(drop=True)}
    n = {len(v["scores"]) for v in out.values()}
    same = all((v["scores"]["image"] == out["A0"]["scores"]["image"]).all() for v in out.values())
    if len(n) != 1 or not same:
        raise DemoError("the four arms were not scored on the same images; refusing to compare them (run scripts/phase8_report.py to see the check)")
    return out


def _review_notes() -> dict:
    p = REPO / "docs" / "results" / "visual_review.json"
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else {}


def case_notes(case: int) -> list:
    r = _review_notes()
    notes = []
    if case in r.get("devices_confirmed_full_resolution", []):
        notes.append("reviewer note (qualitative): C draws a device-like object (pacemaker/ICD generator) that is not in the original")
    elif case in r.get("device_like_objects_less_certain", []):
        notes.append("reviewer note (qualitative): a device-like object is possible in C (less certain)")
    if case in r.get("c_extreme_cardiac_shadow", []):
        notes.append("reviewer note (qualitative): C's cardiac shadow is extreme here")
    return notes


def cmd_cases(art: dict) -> str:
    rows = ["case  patient        " + "  ".join(f"{a:>5} p / PSNR" for a in ARMS)]
    ref = art["A0"]["scores"]
    for i in range(len(ref)):
        cells = []
        for a in ARMS:
            r = art[a]["scores"].iloc[i]
            cells.append(f"{r['p_target_cf']:.2f} / {r['psnr_recon_cf']:4.1f}dB")
        flag = " *" if case_notes(int(ref.iloc[i]["index"])) else ""
        rows.append(f"{int(ref.iloc[i]['index']):>4}  {ref.iloc[i]['patient']:<13}  " + "   ".join(f"{c:>15}" for c in cells) + flag)
    rows.append("")
    rows.append("p = frozen-classifier p(Cardiomegaly) after the edit; PSNR = fidelity of the edit to the reconstruction. * = reviewer note available in `show`.")
    rows.append(SCORE_NOTE)
    rows.append(DISCLAIMER)
    return "\n".join(rows)


def _gray(path) -> np.ndarray:
    return np.asarray(Image.open(path).convert("L"))


def render_panel(panels: list, title: str, footer_lines: list, out_path: Path, card: dict) -> None:
    """panels: [{"title", "image"(2-D uint8), "diff"(2-D or None), "lines"[str]}]. Writes a PNG whose metadata carries the disclaimer."""
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    n = len(panels)
    fig, axes = plt.subplots(2, n, figsize=(3.0 * n, 6.6), squeeze=False)
    for j, p in enumerate(panels):
        axes[0][j].imshow(p["image"], cmap="gray", vmin=0, vmax=255)
        axes[0][j].set_title(p["title"], fontsize=8)
        axes[0][j].axis("off")
        if p.get("diff") is not None:
            axes[1][j].imshow(p["diff"], cmap="magma", vmin=0, vmax=64)
        axes[1][j].axis("off")
        axes[1][j].text(0.5, -0.04, "\n".join(p["lines"]), transform=axes[1][j].transAxes, ha="center", va="top", fontsize=6.5)
    axes[1][0].text(0.5, 0.5, "row 2: |edit − reconstruction| x4\n(brighter = larger change)", transform=axes[1][0].transAxes, ha="center", va="center", fontsize=7)
    fig.suptitle(title, fontsize=10, y=0.995)
    fig.text(0.5, 0.955, DISCLAIMER, ha="center", va="top", fontsize=7.5, color="white", bbox={"facecolor": "#b00020", "edgecolor": "none", "pad": 3})
    fig.text(0.5, 0.012, "\n".join(footer_lines), ha="center", va="bottom", fontsize=6.5, wrap=True)
    fig.subplots_adjust(top=0.88, bottom=0.20, hspace=0.32, wspace=0.04)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out_path, dpi=130, metadata={"Software": None, "Description": DISCLAIMER})
    plt.close(fig)
    (out_path.with_suffix(".json")).write_text(json.dumps({"disclaimer": DISCLAIMER, "score_note": SCORE_NOTE, **card}, indent=2, default=str))


def cmd_show(art: dict, case: int, out_dir: Path) -> Path:
    ref = art["A0"]["scores"]
    if case not in set(ref["index"]):
        raise DemoError(f"unknown case {case}; valid cases: {int(ref['index'].min())}..{int(ref['index'].max())} (run `cases`)")
    row = {a: art[a]["scores"][art[a]["scores"]["index"] == case].iloc[0] for a in ARMS}
    folder = row["A0"]["folder"]
    panels = [{"title": "original (input)", "image": _gray(art["A0"]["run_dir"] / "outputs" / folder / "original.png"), "diff": None,
               "lines": ["real chest X-ray, center-cropped", "(the only non-synthetic panel)"]}]
    card = {"case": case, "operation": "add Cardiomegaly", "evaluation_split": "held-out test patients", "arms": {}}
    for a in ARMS:
        d = art[a]["run_dir"] / "outputs" / folder
        edit, recon = _gray(d / "counterfactual.png"), _gray(d / "reconstructed.png")
        diff = np.abs(edit.astype(np.int16) - recon.astype(np.int16)).astype(np.uint8) * 4
        r = row[a]
        lines = [f"p(Cardiomegaly) {r['p_target_recon']:.2f} → {r['p_target_cf']:.2f} (classifier)", f"PSNR {r['psnr_recon_cf']:.1f} dB · pixels changed {100 * r['change_frac_changed_gt20']:.0f}%", ARM_FINDING[a]]
        panels.append({"title": ARM_TITLE[a] + "\nSYNTHETIC", "image": edit, "diff": np.clip(diff, 0, 255), "lines": lines})
        card["arms"][a] = {"folder": folder, "p_target_recon": float(r["p_target_recon"]), "p_target_after_edit": float(r["p_target_cf"]), "delta_p": float(r["dp_target"]),
                           "psnr_recon_vs_edit_db": float(r["psnr_recon_cf"]), "pixels_changed_gt20_fraction": float(r["change_frac_changed_gt20"]), "finding_from_report": ARM_FINDING[a]}
    notes = case_notes(case)
    footer = [SCORE_NOTE] + notes + ["Full results, limitations and the conclusion that the hypothesis was not supported: docs/FINAL_RESEARCH_REPORT.md"]
    card["reviewer_notes_qualitative"] = notes
    out = Path(out_dir) / f"case_{case:02d}_panel.png"
    render_panel(panels, f"Case {case}: add Cardiomegaly — A0 / A-ft / B / C (saved evaluation outputs; not a diagnosis)", footer, out, card)
    return out


# ----------------------------------------------------------------------------- live generation (the existing pipeline)
def build_generate_config(args) -> dict:
    from src.utils.config import apply_overrides, load_config

    if args.arm != "A0" and not args.delta:
        raise DemoError(f"arm {args.arm} needs its trained weight overlay: pass --delta <delta_final.safetensors> (not in the repository; produced on Kaggle by the Phase 6/7 notebooks)")
    if args.arm == "A0" and args.delta:
        raise DemoError("arm A0 is the untouched PRISM checkpoint: do not pass --delta")
    cfg = load_config(str(REPO / "configs" / "baseline.yaml"))
    cfg["model"]["device"] = args.device
    if args.prism_checkpoint:
        cfg["model"]["finetuned_checkpoint_path"] = args.prism_checkpoint
    if args.delta:
        cfg["model"]["delta_checkpoint_path"] = args.delta
    cfg.setdefault("evaluation", {})["compute_clip_metrics"] = bool(args.clip)
    return apply_overrides(cfg, args.overrides or [])


def check_generate_inputs(cfg: dict, args) -> list:
    problems = []
    if not Path(args.image).exists():
        problems.append(f"input image not found: {args.image}")
    model = cfg["model"]
    if model.get("ldm_type") == "finetuned_chexpert" and not (model.get("finetuned_checkpoint_path") and Path(model["finetuned_checkpoint_path"]).exists()):
        problems.append(f"PRISM checkpoint not found: {model.get('finetuned_checkpoint_path')!r} (python scripts/download_prism_checkpoint.py --dest <dir>; pass --prism-checkpoint)")
    if model.get("delta_checkpoint_path") and not Path(model["delta_checkpoint_path"]).exists():
        problems.append(f"weight overlay not found: {model['delta_checkpoint_path']}")
    if model.get("device") == "cuda":
        import torch

        if not torch.cuda.is_available():
            problems.append("device cuda requested but torch.cuda.is_available() is False (a 512 px inversion on CPU takes hours; use a GPU or Kaggle)")
    return problems


def cmd_generate(args) -> Path:
    cfg = build_generate_config(args)
    problems = check_generate_inputs(cfg, args)
    if problems:
        raise DemoError("cannot run:\n  - " + "\n  - ".join(problems))
    if (args.pathology, args.operation) != EVALUATED:
        print(f"WARNING: only '{EVALUATED[1]} {EVALUATED[0]}' was evaluated in this project (docs/FINAL_RESEARCH_REPORT.md section 5); "
              f"'{args.operation} {args.pathology}' is untested and its outputs have no evidence behind them.")
    from src.evaluation.counterfactual_metrics import change_stats, psnr, ssim
    from src.inference.prism_baseline import PrismCounterfactualGenerator

    from src.utils.config import load_config

    reference = load_config(str(REPO / "configs" / "baseline.yaml"))["editing"]
    keys = ("image_size", "num_ddim_steps", "num_inner_steps", "self_replace_steps", "cross_replace_steps", "edit_word_weight", "guidance_scale")
    deviating = {k: cfg["editing"].get(k) for k in keys if cfg["editing"].get(k) != reference.get(k)}
    if deviating:
        print(f"WARNING: settings differ from the evaluation settings (configs/baseline.yaml): {deviating}. Outputs are NOT comparable to the reported results.")
    result = PrismCounterfactualGenerator(cfg).generate(args.image, args.pathology, operation=args.operation)
    out_dir = Path(args.out)
    saved = result.save(str(out_dir / "outputs"))
    orig, recon, edit = (np.asarray(im.convert("L")) for im in (result.original_image, result.reconstructed_image, result.counterfactual_image))
    cs = change_stats(recon, edit)
    lines_edit = [f"PSNR {psnr(recon, edit):.1f} dB · SSIM {ssim(recon, edit):.3f}", f"pixels changed {100 * cs['frac_changed_gt20']:.0f}%"]
    card = {"mode": "generate", "arm": args.arm, "operation": f"{args.operation} {args.pathology}", "image_input": Path(args.image).name,
            "settings_match_evaluation": not deviating, "settings_that_differ_from_evaluation": deviating,
            "metrics_vs_reconstruction": {"psnr_db": psnr(recon, edit), "ssim": ssim(recon, edit), "pixels_changed_gt20_fraction": cs["frac_changed_gt20"], "brightness_shift": cs["brightness_shift"]},
            "inversion_fidelity_psnr_db": psnr(orig, recon), "inference_info": result.inference_info, "outputs_dir": saved}
    if args.classifier:
        import torch

        from src.data.transforms import build_transforms
        from src.losses.disease_consistency import FrozenClassifier
        from src.utils.config import load_config

        sha = args.classifier_sha or load_config(str(REPO / "configs" / "disease_consistency.yaml"))["classifier_sha256"]
        clf = FrozenClassifier(args.classifier, sha, "cpu")
        tf = build_transforms(clf.image_size, train=False)
        ti = clf.findings.index(args.pathology) if args.pathology in clf.findings else None
        if ti is not None:
            with torch.no_grad():
                p = [float(torch.sigmoid(clf.net(tf(im.convert("RGB")).unsqueeze(0)))[0][ti]) for im in (result.reconstructed_image, result.counterfactual_image)]
            card["frozen_classifier_p"] = {"reconstruction": p[0], "edit": p[1], "note": SCORE_NOTE}
            lines_edit.insert(0, f"p({args.pathology}) {p[0]:.2f} → {p[1]:.2f} (classifier)")
    diff = np.clip(np.abs(edit.astype(np.int16) - recon.astype(np.int16)) * 4, 0, 255).astype(np.uint8)
    panels = [{"title": "original (input)", "image": orig, "diff": None, "lines": ["real chest X-ray, center-cropped"]},
              {"title": "reconstruction\n(inversion check)", "image": recon, "diff": None, "lines": [f"PSNR(orig, recon) {psnr(orig, recon):.1f} dB"]},
              {"title": f"{ARM_TITLE[args.arm]}\nSYNTHETIC edit", "image": edit, "diff": diff, "lines": lines_edit}]
    panel = out_dir / "panel.png"
    footer = [SCORE_NOTE] + ([f"REDUCED SETTINGS {deviating}: not comparable to the evaluated results"] if deviating else []) + ["Limitations and evidence: docs/FINAL_RESEARCH_REPORT.md"]
    render_panel(panels, f"Live generation, arm {args.arm}: {args.operation} {args.pathology} (not a diagnosis)", footer, panel, card)
    return panel


# ----------------------------------------------------------------------------- CLI
def build_parser() -> argparse.ArgumentParser:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="command", required=True)
    for name in ("cases", "show"):
        sp = sub.add_parser(name, help="uses the saved Phase 6 v2 / Phase 7 Kaggle outputs (CPU, offline)")
        sp.add_argument("--phase6-op", default=os.environ.get("PRISM_PHASE6_OP"), help="Phase 6 v2 output directory (env PRISM_PHASE6_OP)")
        sp.add_argument("--phase7-op", default=os.environ.get("PRISM_PHASE7_OP"), help="Phase 7 output directory (env PRISM_PHASE7_OP)")
        if name == "show":
            sp.add_argument("--case", type=int, required=True, help="evaluation case index (see `cases`)")
            sp.add_argument("--out", default=str(REPO / "experiments" / "phase9"), help="output directory (default is git-ignored: the panel contains CheXpert-derived images)")
    g = sub.add_parser("generate", help="live generation with the existing pipeline (GPU + checkpoints needed)")
    g.add_argument("--image", required=True)
    g.add_argument("--arm", required=True, choices=ARMS)
    g.add_argument("--delta", help="trained weight overlay delta_final.safetensors of arm A-ft / B / C")
    g.add_argument("--prism-checkpoint", help="PRISM CheXpert checkpoint (model.safetensors)")
    g.add_argument("--device", default="cuda", choices=["cuda", "cpu"])
    g.add_argument("--pathology", default=EVALUATED[0])
    g.add_argument("--operation", default=EVALUATED[1], choices=["add", "remove"])
    g.add_argument("--classifier", help="optional frozen classifier best.pt (SHA-256-pinned) to print its score")
    g.add_argument("--classifier-sha")
    g.add_argument("--clip", action="store_true", help="also compute CLIP similarity (downloads a CLIP model)")
    g.add_argument("--out", default=str(REPO / "experiments" / "phase9" / "generated"))
    g.add_argument("--set", dest="overrides", action="append", default=[], metavar="dotted.key=value", help="config override (as in scripts/run_experiment.py)")
    g.add_argument("--dry-run", action="store_true", help="resolve and validate the configuration and the inputs, load no model")
    return ap


def main(argv=None) -> int:
    args = build_parser().parse_args(argv)
    try:
        if args.command in ("cases", "show"):
            art = locate_artifacts(args.phase6_op, args.phase7_op)
            if args.command == "cases":
                print(cmd_cases(art))
            else:
                out = cmd_show(art, args.case, Path(args.out))
                print(DISCLAIMER)
                print(f"panel: {out}\ncard:  {out.with_suffix('.json')}")
            return 0
        cfg = build_generate_config(args)
        if args.dry_run:
            problems = check_generate_inputs(cfg, args)
            print(DISCLAIMER)
            print(json.dumps({"arm": args.arm, "model": cfg["model"], "editing": cfg["editing"]}, indent=2, default=str))
            if problems:
                print("would NOT run:\n  - " + "\n  - ".join(problems))
                return 2
            print("dry run OK: configuration and inputs are valid (no model was loaded)")
            return 0
        panel = cmd_generate(args)
        print(DISCLAIMER)
        print(f"panel: {panel}\ncard:  {panel.with_suffix('.json')}")
        return 0
    except DemoError as e:
        print(f"ERROR: {e}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
